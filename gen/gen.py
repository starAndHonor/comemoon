#!/usr/bin/env python3
"""comemoon code generator: turns `#comemo.track`-annotated MoonBit types
into Call-enum + surface-wrapper boilerplate.

Input:  tracked_user.mbt (user-written, with `#comemo.track` markers)
Output: comemo_gen.mbt (committed; built by the package)

Usage:  python3 gen/gen.py [input] [output]
"""
import re
import sys

IN = sys.argv[1] if len(sys.argv) > 1 else "user_tracked.mbt"
OUT = sys.argv[2] if len(sys.argv) > 2 else "comemo_gen.mbt"

src = open(IN).read()

# Find each `#comemo.track` block: marker + following struct + methods.
# We split the file at marker lines; the tracked type name is the struct
# declared right after the marker.
out = []
out.append("///| GENERATED by gen/gen.py — do not edit by hand.")
out.append("///| Regenerate with: python3 gen/gen.py (via dev_build rule).")
out.append("")

marker_re = re.compile(r"#comemo\.track\s*\n(?:pub\(all\)\s+)?struct\s+(\w+)\s*\{")
# Collect all method signatures: fn Type::method(self, a : T, ...) -> R
method_re = re.compile(
    r"(?:pub\s+)?fn\s+(\w+)::(\w+)\(([^)]*)\)\s*->\s*([^\s{]+)"
)

for m in marker_re.finditer(src):
    type_name = m.group(1)
    # Find the methods belonging to this type: fn Type::method within this block
    block_end = src.find("\n#comemo.", m.end())
    if block_end == -1:
        block_end = len(src)
    block = src[m.end():block_end]

    methods = []
    for mm in method_re.finditer(block):
        tname, mname, params, ret = mm.group(1), mm.group(2), mm.group(3), mm.group(4)
        if tname != type_name:
            continue
        methods.append((mname, params, ret))

    if not methods:
        continue

    # 1. Call enum: one variant per method, args as declared.
    call_enum = type_name + "Call"
    out.append(f"///| Call enum for `{type_name}` (generated).")
    out.append(f"pub(all) enum {call_enum} {{")
    for mname, params, _ret in methods:
        # params: "self, path : String" -> drop self, keep "path : String"
        args = [p.strip() for p in params.split(",") if p.strip() and "self" not in p]
        # Enum variants use positional types only (MoonBit has no labeled
        # payload without the `~` marker).
        types = [a.split(":")[1].strip() for a in args]
        variant = mname[0].upper() + mname[1:]
        if types:
            out.append(f"  {variant}({', '.join(types)})")
        else:
            out.append(f"  {variant}")
    out.append("} derive(Hash, Eq)")
    out.append("")
    def hash_fn_for(t):
        return {
            "String": "hash_string",
            "Int": "hash_int",
            "UInt64": "hash_int",
            "Bool": "hash_bool",
            "Unit": "hash_unit_value",
        }.get(t, f"hash_{t.lower()}")

    def write_fn_for(t):
        return {
            "String": "write_rust_string",
            "Int": "write_rust_i64",
            "Int64": "write_rust_i64",
            "UInt64": "write_rust_u64",
            "Bool": "write_rust_bool",
            "Char": "write_rust_char",
        }.get(t, f"{t}::write_rust".replace("::", "."))

    # RustHashable via write_rust: discriminant (usize, 8 LE bytes) +
    # each field streamed in variant order (mirrors Rust derive(Hash)).
    out.append(f"///| Rust-compatible hashing for `{call_enum}` (generated).")
    out.append(f"pub impl RustHashable for {call_enum} with fn write_rust(self, bytes) {{")
    out.append("  match self {")
    for idx, (mname, params, _ret) in enumerate(methods):
        variant = mname[0].upper() + mname[1:]
        args = [p.strip() for p in params.split(",") if p.strip() and "self" not in p]
        arg_names = [a.split(":")[0].strip() for a in args]
        field_types = [a.split(":")[1].strip() for a in args]
        if arg_names:
            out.append(f"    {variant}({', '.join(arg_names)}) => {{")
        else:
            out.append(f"    {variant} => {{")
        out.append(f"      append_u64_le(bytes, {idx})")
        for (n, t) in zip(arg_names, field_types):
            out.append(f"      {write_fn_for(t)}(bytes, {n})")
        out.append("    }")
    out.append("  }")
    out.append("}")
    out.append("")
    # 2. Surface wrapper: struct + methods that route through Tracked.
    #    Methods returning Unit are treated as mutable (recorded, replayed on
    #    hit); others are immutable (recorded with the return hash).
    surface = type_name + "Tracked"
    out.append(f"///| Surface wrapper for `{type_name}` (generated).")
    out.append(f"pub(all) struct {surface} {{")
    out.append(f"  t : Tracked[{type_name}, {call_enum}]")
    out.append("}")
    out.append("")
    out.append(f"///| Constructs the surface wrapper around a value.")
    out.append(f"pub fn {surface}::new(value : {type_name}) -> {surface} {{")
    out.append(f"  {{ t: Tracked::new(value) }}")
    out.append("}")
    out.append("")
    for mname, params, ret in methods:
        args = [p.strip() for p in params.split(",") if p.strip() and "self" not in p]
        arg_names = [a.split(":")[0].strip() for a in args]
        call_args = ", ".join(arg_names)
        variant = mname[0].upper() + mname[1:]
        ctor = variant if not arg_names else variant + "(" + call_args + ")"
        wrapper_params = ", ".join(args)
        if wrapper_params:
            wrapper_params = ", " + wrapper_params
        inner_args = ", ".join(arg_names)
        is_mutable = ret == "Unit"
        fn_call = "call_mut" if is_mutable else "call"
        call_marker = ""
        out.append(f"pub fn {surface}::{mname}(self : {surface}{wrapper_params}) -> {ret} {{")
        out.append(f"  self.t.{fn_call}({call_enum}::{ctor}, fn(v : {type_name}) -> {ret} {{")
        if inner_args:
            out.append(f"    v.{mname}({inner_args})")
        else:
            out.append(f"    v.{mname}()")
        out.append(f"  }}, {hash_fn_for(ret)})")
        out.append("}")
        out.append("")

open(OUT, "w").write("\n".join(out) + "\n")
print(f"generated {OUT}: {len(out)} lines")

# --- memoize input helper for the generated surface type ---------------------
# For a single-tracked-argument memoized function, emit a helper that builds
# the Input from the surface wrapper. The helper needs the call enum and the
# user's oracle (replay of a call on the tracked value). We emit a skeleton
# that the user completes with their oracle closures.
for m in marker_re.finditer(src):
    pass  # (markers already handled above; helper emitted below)
