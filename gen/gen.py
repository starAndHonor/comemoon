#!/usr/bin/env python3
"""comemoon code generator: turns `#comemo.track`-annotated MoonBit types
into Call-enum + surface-wrapper boilerplate.

Input:  tracked_user.mbt (user-written, with `#comemo.track` markers)
Output: comemo_gen.mbt (committed; built by the package)

Usage:  python3 gen/gen.py [input] [output]
"""
import re
import sys

IN = sys.argv[1] if len(sys.argv) > 1 else "lib/user_tracked.mbt"
OUT = sys.argv[2] if len(sys.argv) > 2 else "lib/comemo_gen.mbt"

src = open(IN).read()
def hash_fn_for_top(t):
    return {
        "String": "hash_string",
        "Int": "hash_int",
        "UInt64": "hash_int",
        "Bool": "hash_bool",
        "Unit": "hash_unit_value",
    }.get(t, f"hash_{t.lower()}")

def write_fn_for_top(t):
    return {
        "String": "write_rust_string",
        "Int": "write_rust_i64",
        "Int64": "write_rust_i64",
        "UInt64": "write_rust_u64",
        "Bool": "write_rust_bool",
        "Char": "write_rust_char",
    }.get(t, f"{t}::write_rust".replace("::", "."))



# Find each `#comemo.track` block: marker + following struct + methods.
# We split the file at marker lines; the tracked type name is the struct
# declared right after the marker.
out = []
out.append("///| GENERATED by gen/gen.py — do not edit by hand.")
out.append("///| Regenerate with: python3 gen/gen.py (via dev_build rule).")
out.append("")

marker_re = re.compile(r"#comemo\.track\s*\n(?:pub\(all\)\s+)?struct\s+(\w+)\s*\{")
# Collect all method signatures: fn Type::method(self, a : T, ...) -> R
method_re = re.compile(
    r"(?:pub\s+)?fn\s+(\w+)::(\w+)\(([^)]*)\)\s*->\s*([^\s{]+)"
)

for m in marker_re.finditer(src):
    type_name = m.group(1)
    # Find the methods belonging to this type: fn Type::method within this block
    block_end = src.find("\n#comemo.", m.end())
    if block_end == -1:
        block_end = len(src)
    block = src[m.end():block_end]

    methods = []
    for mm in method_re.finditer(block):
        tname, mname, params, ret = mm.group(1), mm.group(2), mm.group(3), mm.group(4)
        if tname != type_name:
            continue
        methods.append((mname, params, ret))

    if not methods:
        continue

    # 1. Call enum: one variant per method, args as declared.
    call_enum = type_name + "Call"
    out.append(f"///| Call enum for `{type_name}` (generated).")
    out.append(f"pub(all) enum {call_enum} {{")
    for mname, params, _ret in methods:
        # params: "self, path : String" -> drop self, keep "path : String"
        args = [p.strip() for p in params.split(",") if p.strip() and "self" not in p]
        # Enum variants use positional types only (MoonBit has no labeled
        # payload without the `~` marker).
        types = [a.split(":")[1].strip() for a in args]
        variant = mname[0].upper() + mname[1:]
        if types:
            out.append(f"  {variant}({', '.join(types)})")
        else:
            out.append(f"  {variant}")
    out.append("} derive(Hash, Eq)")
    out.append("")
    def hash_fn_for(t):
        return {
            "String": "hash_string",
            "Int": "hash_int",
            "UInt64": "hash_int",
            "Bool": "hash_bool",
            "Unit": "hash_unit_value",
        }.get(t, f"hash_{t.lower()}")

    def write_fn_for(t):
        return {
            "String": "write_rust_string",
            "Int": "write_rust_i64",
            "Int64": "write_rust_i64",
            "UInt64": "write_rust_u64",
            "Bool": "write_rust_bool",
            "Char": "write_rust_char",
        }.get(t, f"{t}::write_rust".replace("::", "."))

    # RustHashable via write_rust: discriminant (usize, 8 LE bytes) +
    # each field streamed in variant order (mirrors Rust derive(Hash)).
    out.append(f"///| Rust-compatible hashing for `{call_enum}` (generated).")
    out.append(f"pub impl RustHashable for {call_enum} with fn write_rust(self, bytes) {{")
    out.append("  match self {")
    for idx, (mname, params, _ret) in enumerate(methods):
        variant = mname[0].upper() + mname[1:]
        args = [p.strip() for p in params.split(",") if p.strip() and "self" not in p]
        arg_names = [a.split(":")[0].strip() for a in args]
        field_types = [a.split(":")[1].strip() for a in args]
        if arg_names:
            out.append(f"    {variant}({', '.join(arg_names)}) => {{")
        else:
            out.append(f"    {variant} => {{")
        out.append(f"      append_u64_le(bytes, {idx})")
        for (n, t) in zip(arg_names, field_types):
            out.append(f"      {write_fn_for(t)}(bytes, {n})")
        out.append("    }")
    out.append("  }")
    out.append("}")
    out.append("")
    # 2. Surface wrapper: struct + methods that route through Tracked.
    #    Methods returning Unit are treated as mutable (recorded, replayed on
    #    hit); others are immutable (recorded with the return hash).
    surface = type_name + "Tracked"
    out.append(f"///| Surface wrapper for `{type_name}` (generated).")
    out.append(f"pub(all) struct {surface} {{")
    out.append(f"  t : Tracked[{type_name}, {call_enum}]")
    out.append("}")
    out.append("")
    out.append(f"///| Constructs the surface wrapper around a value.")
    out.append(f"pub fn {surface}::new(value : {type_name}) -> {surface} {{")
    out.append(f"  {{ t: Tracked::new(value) }}")
    out.append("}")
    out.append("")
    for mname, params, ret in methods:
        args = [p.strip() for p in params.split(",") if p.strip() and "self" not in p]
        arg_names = [a.split(":")[0].strip() for a in args]
        call_args = ", ".join(arg_names)
        variant = mname[0].upper() + mname[1:]
        ctor = variant if not arg_names else variant + "(" + call_args + ")"
        wrapper_params = ", ".join(args)
        if wrapper_params:
            wrapper_params = ", " + wrapper_params
        inner_args = ", ".join(arg_names)
        is_mutable = ret == "Unit"
        fn_call = "call_mut" if is_mutable else "call"
        call_marker = ""
        out.append(f"pub fn {surface}::{mname}(self : {surface}{wrapper_params}) -> {ret} {{")
        out.append(f"  self.t.{fn_call}({call_enum}::{ctor}, fn(v : {type_name}) -> {ret} {{")
        if inner_args:
            out.append(f"    v.{mname}({inner_args})")
        else:
            out.append(f"    v.{mname}()")
        out.append(f"  }}, {hash_fn_for(ret)})")
        out.append("}")
        out.append("")

# --- Trait track: #comemo.track on a trait -> generic surface ----------------
# Trait methods are declared as `fetch(Self, key : String) -> Int` (no fn
# prefix in the trait body). Produces a generic surface WorldTracked[T].
trait_marker_re = re.compile(
    r"#comemo\.track\s*\n(?:pub(?:\s*\(open\))?\s+)?trait\s+(\w+)\s*\{"
)
trait_method_re = re.compile(r"(\w+)\(Self([^)]*)\)\s*->\s*([^\s{]+)")

for tm in trait_marker_re.finditer(src):
    trait_name = tm.group(1)
    block_end = src.find("\n#comemo.", tm.end())
    if block_end == -1:
        block_end = len(src)
    block = src[tm.end():block_end]

    methods = []
    for mm in trait_method_re.finditer(block):
        mname = mm.group(1)
        params = "self" + (mm.group(2) or "")
        ret = mm.group(3)
        methods.append((mname, params, ret))

    if not methods:
        continue

    call_enum = trait_name + "Call"
    out.append(f"///| Call enum for trait `{trait_name}` (generated).")
    out.append(f"pub(all) enum {call_enum} {{")
    for mname, params, _ret in methods:
        args = [p.strip() for p in params.split(",") if p.strip() and "self" not in p]
        types = [a.split(":")[1].strip() for a in args]
        variant = mname[0].upper() + mname[1:]
        if types:
            out.append(f"  {variant}({', '.join(types)})")
        else:
            out.append(f"  {variant}")
    out.append("} derive(Hash, Eq)")
    out.append("")
    out.append(f"pub impl RustHashable for {call_enum} with fn write_rust(self, bytes) {{")
    out.append("  match self {")
    for idx, (mname, params, _ret) in enumerate(methods):
        variant = mname[0].upper() + mname[1:]
        args = [p.strip() for p in params.split(",") if p.strip() and "self" not in p]
        arg_names = [a.split(":")[0].strip() for a in args]
        field_types = [a.split(":")[1].strip() for a in args]
        if arg_names:
            out.append(f"    {variant}({', '.join(arg_names)}) => {{")
        else:
            out.append(f"    {variant} => {{")
        out.append(f"      append_u64_le(bytes, {idx})")
        for (n, t) in zip(arg_names, field_types):
            out.append(f"      {write_fn_for_top(t)}(bytes, {n})")
        out.append("    }")
    out.append("  }")
    out.append("}")
    out.append("")
    surface = trait_name + "Tracked"
    out.append(f"///| Generic surface wrapper for trait `{trait_name}` (generated).")
    out.append(f"pub(all) struct {surface}[T] {{")
    out.append(f"  t : Tracked[T, {call_enum}]")
    out.append("}")
    out.append("")
    out.append(f"pub fn[T] {surface}::new(value : T) -> {surface}[T] {{")
    out.append(f"  {{ t: Tracked::new(value) }}")
    out.append("}")
    out.append("")
    for mname, params, ret in methods:
        args = [p.strip() for p in params.split(",") if p.strip() and "self" not in p]
        arg_names = [a.split(":")[0].strip() for a in args]
        call_args = ", ".join(arg_names)
        variant = mname[0].upper() + mname[1:]
        ctor = variant if not arg_names else variant + "(" + call_args + ")"
        wrapper_params = ", ".join(args)
        if wrapper_params:
            wrapper_params = ", " + wrapper_params
        inner_args = ", ".join(arg_names)
        out.append(f"pub fn[T : {trait_name}] {surface}::{mname}(self : {surface}[T]{wrapper_params}) -> {ret} {{")
        out.append(f"  self.t.call({call_enum}::{ctor}, fn(v : T) -> {ret} {{")
        if inner_args:
            out.append(f"    {trait_name}::{mname}(v, {inner_args})")
        else:
            out.append(f"    {trait_name}::{mname}(v)")
        out.append(f"  }}, {hash_fn_for_top(ret)})")
        out.append("}")
        out.append("")


open(OUT, "w").write("\n".join(out) + "\n")
print(f"generated {OUT}: {len(out)} lines")

# --- memoize input helper for the generated surface type ---------------------
# For a single-tracked-argument memoized function, emit a helper that builds
# the Input from the surface wrapper. The helper needs the call enum and the
# user's oracle (replay of a call on the tracked value). We emit a skeleton
# that the user completes with their oracle closures.
for m in marker_re.finditer(src):
    pass  # (markers already handled above; helper emitted below)

# --- Multi-tracked memoize (mirrors Rust Multi<(...)>) -----------------------
# Syntax in user_tracked.mbt:
#   #comemo.memoize2 A B
#   fn evaluate(a : ATracked, b : BTracked, script : String) -> Int
#
# Produces: merged Call enum (A_B_Call), the surface wrappers are already
# generated by the #comemo.track markers; here we emit the memoize2 call
# wrapper that routes both tracked params' calls into the merged enum.
memoize2_re = re.compile(
    r"#comemo\.memoize2\s+(\w+)\s+(\w+)\s*\n"
    r"(?:pub\s+)?fn\s+(\w+)\(([^)]*)\)\s*->\s*(\w+)"
)
for m in memoize2_re.finditer(src):
    ta, tb, fname, params, fret = m.group(1), m.group(2), m.group(3), m.group(4), m.group(5)
    # Tracked params are the first two (by convention); rest are plain args.
    # We emit a helper that builds the Input2 wiring for the user's fn body.
    merged = f"{ta}_{tb}_Call"
    out.append(f"///| Merged call enum for `{fname}` (two tracked params, generated).")
    out.append(f"pub(all) enum {merged} {{")
    out.append(f"  A({ta}Call)")
    out.append(f"  B({tb}Call)")
    out.append("} derive(Hash, Eq)")
    out.append("")
    out.append(f"pub impl RustHashable for {merged} with fn write_rust(self, bytes) {{")
    out.append("  match self {")
    out.append(f"    A(c) => {{ append_u64_le(bytes, 0); c.write_rust(bytes) }}")
    out.append(f"    B(c) => {{ append_u64_le(bytes, 1); c.write_rust(bytes) }}")
    out.append("  }")
    out.append("}")
    out.append("")
    out.append(f"///| Call wrapper for `{fname}` — the user calls this instead of")
    out.append(f"///| the raw memoize2, with both tracked params already wrapped.")
    out.append(f"pub fn {fname}_with(a : {ta}Tracked, b : {tb}Tracked, key_fn : () -> UInt128, body : (() -> Int)) -> Int {{")
    out.append(f"  let at = a.t")
    out.append(f"  let bt = b.t")
    out.append(f"  memoize2({fname}_cache, Input2::new(")
    out.append("    key_fn,")
    out.append(f"    fn(rec : Recorder[{merged}]) -> (Recorder[{ta}Call]?, Recorder[{tb}Call]?) {{")
    out.append(f"      let p1 = at.attach(fn(c : {ta}Call, h : UInt128, ret : UInt128, m : Bool) -> Unit {{ rec({merged}::A(c), h, ret, m) }})")
    out.append(f"      let p2 = bt.attach(fn(c : {tb}Call, h : UInt128, ret : UInt128, m : Bool) -> Unit {{ rec({merged}::B(c), h, ret, m) }})")
    out.append("      (p1, p2)")
    out.append("    },")
    out.append(f"    fn(c : {merged}) -> UInt128 {{")
    out.append("      match c {")
    out.append(f"        A(ca) => at.validate(ca, fn(x : {ta}) -> Int {{ 0 }}, test_hash_int)")
    out.append(f"        B(cb) => bt.validate(cb, fn(x : {tb}) -> Int {{ 0 }}, test_hash_int)")
    out.append("      }")
    out.append("    },")
    out.append(f"    fn(_c : {merged}) -> Unit {{ () }},")
    out.append(f"    fn(prev : (Recorder[{ta}Call]?, Recorder[{tb}Call]?)) -> Unit {{ let (p1, p2) = prev; at.detach(p1); bt.detach(p2) }},")
    out.append("  ), true, body)")
    out.append("}")
    out.append("")
